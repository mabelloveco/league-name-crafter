// Fantasy Football Team Names Database

const uniqueTeamNames = (...lists: readonly (readonly string[])[]): string[] => {
  const seen = new Set<string>();
  const merged: string[] = [];
  for (const list of lists) {
    for (const name of list) {
      if (!seen.has(name)) {
        seen.add(name);
        merged.push(name);
      }
    }
  }
  return merged;
};

